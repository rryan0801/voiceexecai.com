import { createClientFromRequest } from 'npm:@base44/sdk@0.8.25';

Deno.serve(async (req) => {
  // This endpoint is called by email tracking pixel (no auth required)
  try {
    const url = new URL(req.url);
    const emailId = url.pathname.split('/').pop();

    if (!emailId) {
      return Response.json({ error: 'Invalid email ID' }, { status: 400 });
    }

    // Use service role to update tracking without user auth
    const base44 = createClientFromRequest(req);

    // Find the tracking event
    const events = await base44.asServiceRole.entities.EmailTrackingEvent.filter(
      { email_id: emailId },
      '-created_date',
      1
    );

    if (!events || events.length === 0) {
      // Return transparent pixel regardless (don't leak info)
      return new Response(new Uint8Array([0x47, 0x49, 0x46, 0x38, 0x39, 0x61, 0x01, 0x00, 0x01, 0x00, 0x80, 0x00, 0x00, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0x21, 0xf9, 0x04, 0x01, 0x0a, 0x00, 0x01, 0x00, 0x2c, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0x02, 0x02, 0x4c, 0x01, 0x00, 0x3b]), {
        headers: { 'Content-Type': 'image/gif' }
      });
    }

    const event = events[0];
    const now = new Date().toISOString();

    // Update tracking
    await base44.asServiceRole.entities.EmailTrackingEvent.update(event.id, {
      open_count: (event.open_count || 0) + 1,
      first_open_at: event.first_open_at || now,
      last_open_at: now,
      status: 'opened',
      engagement_score: Math.min(100, (event.engagement_score || 0) + 20)
    });

    // Return transparent GIF pixel
    return new Response(new Uint8Array([0x47, 0x49, 0x46, 0x38, 0x39, 0x61, 0x01, 0x00, 0x01, 0x00, 0x80, 0x00, 0x00, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0x21, 0xf9, 0x04, 0x01, 0x0a, 0x00, 0x01, 0x00, 0x2c, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0x02, 0x02, 0x4c, 0x01, 0x00, 0x3b]), {
      headers: { 'Content-Type': 'image/gif' }
    });
  } catch (error) {
    console.error('Error recording email open:', error);
    // Still return pixel on error
    return new Response(new Uint8Array([0x47, 0x49, 0x46, 0x38, 0x39, 0x61, 0x01, 0x00, 0x01, 0x00, 0x80, 0x00, 0x00, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0x21, 0xf9, 0x04, 0x01, 0x0a, 0x00, 0x01, 0x00, 0x2c, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0x02, 0x02, 0x4c, 0x01, 0x00, 0x3b]), {
      headers: { 'Content-Type': 'image/gif' }
    });
  }
});